#include <iostream>
using namespace std;

int main() {
    int a, b; // Variables para guardar los números

    cout << "Introduce el primer número: ";
    cin >> a;

    cout << "Introduce el segundo número: ";
    cin >> b;

    int suma = a + b;

    cout << "La suma de " << a << " y " << b << " es: " << suma << endl;

    return 0;
}
